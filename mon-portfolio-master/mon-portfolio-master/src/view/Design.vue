<script>
export default {
  name: "DesignPage",

  data() {
    return {
      isLightboxOpen: false,
      currentIndex: 0,
      images: [],
    };
  },

  computed: {
    currentImage() {
      return this.images[this.currentIndex] || null;
    },
  },

  methods: {
    refreshImages() {
      const nodes = document.querySelectorAll(".image-box img, .banner-box img");
      this.images = Array.from(nodes).map((img) => ({
        src: img.currentSrc || img.src || img.getAttribute("src"),
        alt: img.alt || "Création graphique par Amin Miladi",
      }));
    },

    openLightbox(index) {
      if (!this.images.length) return;
      this.currentIndex = index;
      this.isLightboxOpen = true;
      document.body.style.overflow = "hidden";
    },

    closeLightbox() {
      this.isLightboxOpen = false;
      document.body.style.overflow = "";
    },

    nextImage() {
      if (!this.images.length) return;
      this.currentIndex = (this.currentIndex + 1) % this.images.length;
    },

    prevImage() {
      if (!this.images.length) return;
      this.currentIndex = (this.currentIndex - 1 + this.images.length) % this.images.length;
    },

    onDocumentClick(e) {
      const box = e.target.closest(".image-box") || e.target.closest(".banner-box");
      if (!box) return;

      const boxes = Array.from(document.querySelectorAll(".image-box, .banner-box"));
      const index = boxes.indexOf(box);
      if (index === -1) return;

      this.refreshImages();
      this.openLightbox(index);
    },

    handleKeydown(e) {
      if (!this.isLightboxOpen) return;
      if (e.key === "Escape") this.closeLightbox();
      if (e.key === "ArrowRight") this.nextImage();
      if (e.key === "ArrowLeft") this.prevImage();
    },

    initScrollReveal() {
      const observer = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.classList.add("active");
          }
        });
      }, { threshold: 0.05 });

      document.querySelectorAll(".reveal-section").forEach((section) => {
        observer.observe(section);
      });
    },

    setSEO() {
      document.title = "Design Graphique & Illustrations | Portfolio - Amin Miladi";
      
      const currentUrl = window.location.href;
      const descText = "Parcourez la galerie de designs graphiques et d'illustrations d'Amin Miladi. Affiches de films, flyers Sushi Thai, branding de luxe (Mayel), packagings Sapik et travaux multimédias.";

      const updateMeta = (attr, value, content) => {
        let el = document.querySelector(`meta[${attr}="${value}"]`);
        if (!el) {
          el = document.createElement('meta');
          el.setAttribute(attr, value);
          document.head.appendChild(el);
        }
        el.content = content;
      };

      updateMeta('name', 'description', descText);
      updateMeta('name', 'keywords', "Amin Miladi, design graphique, sushi thai flyer, illustration vectorielle, affiche cinéma, Prison Break poster, Sapik packaging, mockup, Adobe, portfolio MMI");
      updateMeta('name', 'robots', "index, follow, max-image-preview:large");

      updateMeta('property', 'og:site_name', "Amin Miladi - Portfolio");
      updateMeta('property', 'og:title', "Design Graphique & Illustrations de Collection - Amin Miladi");
      updateMeta('property', 'og:description', descText);
      updateMeta('property', 'og:type', "website");
      updateMeta('property', 'og:url', currentUrl);

      updateMeta('name', 'twitter:card', "summary_large_image");
      updateMeta('name', 'twitter:title', "Galerie d'Art Graphique & Design - Amin Miladi");
      updateMeta('name', 'twitter:description', descText);

      const oldScript = document.getElementById('gallery-seo-ld');
      if (oldScript) oldScript.remove();

      const jsonLd = {
        "@context": "https://schema.org",
        "@graph": [
          {
            "@type": "ImageGallery",
            "@id": currentUrl + "#gallery",
            "url": currentUrl,
            "name": "Galerie de Design Visuel et d'Illustrations Éditoriales - Amin Miladi",
            "description": descText,
            "author": {
              "@type": "Person",
              "name": "Amin Miladi",
              "jobTitle": "Graphiste & Vidéaste"
            },
            "creator": {
              "@type": "Person",
              "name": "Amin Miladi"
            }
          },
          {
            "@type": "BreadcrumbList",
            "@id": currentUrl + "#breadcrumb",
            "itemListElement": [
              {
                "@type": "ListItem",
                "position": 1,
                "name": "Accueil",
                "item": window.location.origin + "/accueil"
              },
              {
                "@type": "ListItem",
                "position": 2,
                "name": "Projets",
                "item": window.location.origin + "/projets"
              },
              {
                "@type": "ListItem",
                "position": 3,
                "name": "Design & Illustrations",
                "item": currentUrl
              }
            ]
          }
        ]
      };

      const script = document.createElement('script');
      script.id = "gallery-seo-ld";
      script.type = "application/ld+json";
      script.text = JSON.stringify(jsonLd);
      document.head.appendChild(script);
    }
  },

  mounted() {
    this.refreshImages();
    document.addEventListener("click", this.onDocumentClick);
    window.addEventListener("keydown", this.handleKeydown);
    this.initScrollReveal();
    this.setSEO();
  },

  beforeUnmount() {
    document.removeEventListener("click", this.onDocumentClick);
    window.removeEventListener("keydown", this.handleKeydown);
    document.body.style.overflow = "";
  },
};
</script>

